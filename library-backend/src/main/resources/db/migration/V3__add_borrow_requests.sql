-- V3: member borrowing requests reviewed by librarians/admins.
--
-- A request is created by a MEMBER and starts as PENDING. A LIBRARIAN or
-- ADMIN either rejects it or approves it. Approval issues one available
-- physical copy and links the request to the created loan.
--
-- Completed requests stay in this table as history.

CREATE TABLE public.borrow_request (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.borrow_request_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
    ),
    book_id integer NOT NULL,
    member_id integer NOT NULL,
    requested_at timestamp with time zone NOT NULL,
    status character varying(16) NOT NULL DEFAULT 'PENDING',
    reviewed_by integer,
    reviewed_at timestamp with time zone,
    loan_id integer,
    CONSTRAINT borrow_request_pkey PRIMARY KEY (id),
    CONSTRAINT borrow_request_book_id_fkey FOREIGN KEY (book_id) REFERENCES public.book(id),
    CONSTRAINT borrow_request_member_id_fkey FOREIGN KEY (member_id) REFERENCES public.users(id),
    CONSTRAINT borrow_request_reviewed_by_fkey FOREIGN KEY (reviewed_by) REFERENCES public.users(id),
    CONSTRAINT borrow_request_loan_id_fkey FOREIGN KEY (loan_id) REFERENCES public.loan(id),
    CONSTRAINT borrow_request_loan_id_key UNIQUE (loan_id),
    CONSTRAINT borrow_request_status_check CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_borrow_request_book_id ON public.borrow_request (book_id);
CREATE INDEX idx_borrow_request_member_id ON public.borrow_request (member_id);
CREATE INDEX idx_borrow_request_status ON public.borrow_request (status);
CREATE INDEX idx_borrow_request_requested_at ON public.borrow_request (requested_at);

-- A member may have at most one PENDING request for the same book.
-- APPROVED and REJECTED rows are excluded so request history is preserved.
CREATE UNIQUE INDEX uq_borrow_request_pending_member_book
    ON public.borrow_request (member_id, book_id)
    WHERE status = 'PENDING';
