-- V2: additive book metadata, physical book copies, and borrowing history.
--
-- This migration is additive. It does not modify V1, does not drop or rename
-- existing columns, and does not rewrite existing rows. book.user_id is kept
-- temporarily for backward compatibility with the current application.
--
-- Existing borrowing data is migrated as follows:
--   * every existing book receives exactly one physical copy
--     (copy_code = 'LEGACY-<book_id>')
--   * copies of books with a borrower are ON_LOAN, otherwise AVAILABLE
--   * every book with a borrower receives one ACTIVE legacy loan
--   * legacy loans leave issue_date, due_date, returned_at, and issued_by NULL
--     because the previous system never recorded those values
--   * no fines or notifications are generated

-- ---------------------------------------------------------------------------
-- 1. Additional book information (all nullable; no invented values)
-- ---------------------------------------------------------------------------

ALTER TABLE public.book
    ADD COLUMN description text,
    ADD COLUMN isbn character varying(32),
    ADD COLUMN publisher character varying(255),
    ADD COLUMN published_year integer,
    ADD COLUMN language character varying(64),
    ADD COLUMN page_count integer;

-- ---------------------------------------------------------------------------
-- 2. Physical copies
-- ---------------------------------------------------------------------------

CREATE TABLE public.book_copy (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.book_copy_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
    ),
    book_id integer NOT NULL,
    copy_code character varying(64) NOT NULL,
    status character varying(16) NOT NULL DEFAULT 'AVAILABLE',
    CONSTRAINT book_copy_pkey PRIMARY KEY (id),
    CONSTRAINT book_copy_copy_code_key UNIQUE (copy_code),
    CONSTRAINT book_copy_book_id_fkey FOREIGN KEY (book_id) REFERENCES public.book(id),
    CONSTRAINT book_copy_status_check CHECK (
        status IN ('AVAILABLE', 'ON_LOAN', 'LOST', 'DAMAGED', 'WITHDRAWN')
    )
);

CREATE INDEX idx_book_copy_book_id ON public.book_copy (book_id);
CREATE INDEX idx_book_copy_status ON public.book_copy (status);

-- One initial copy for every existing book. Books currently assigned to a
-- borrower are on loan; the others are available.
INSERT INTO public.book_copy (book_id, copy_code, status)
SELECT
    b.id,
    'LEGACY-' || b.id,
    CASE WHEN b.user_id IS NULL THEN 'AVAILABLE' ELSE 'ON_LOAN' END
FROM public.book b;

-- ---------------------------------------------------------------------------
-- 3. Borrowing history
-- ---------------------------------------------------------------------------

CREATE TABLE public.loan (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.loan_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
    ),
    copy_id integer NOT NULL,
    member_id integer NOT NULL,
    issued_by integer,
    issue_date timestamp with time zone,
    due_date timestamp with time zone,
    returned_at timestamp with time zone,
    status character varying(16) NOT NULL DEFAULT 'ACTIVE',
    is_legacy boolean NOT NULL DEFAULT false,
    CONSTRAINT loan_pkey PRIMARY KEY (id),
    CONSTRAINT loan_copy_id_fkey FOREIGN KEY (copy_id) REFERENCES public.book_copy(id),
    CONSTRAINT loan_member_id_fkey FOREIGN KEY (member_id) REFERENCES public.users(id),
    CONSTRAINT loan_issued_by_fkey FOREIGN KEY (issued_by) REFERENCES public.users(id),
    CONSTRAINT loan_status_check CHECK (status IN ('ACTIVE', 'RETURNED'))
);

-- More than one ACTIVE loan for the same physical copy is invalid.
-- RETURNED loans are excluded so they remain as history.
CREATE UNIQUE INDEX uq_loan_active_copy
    ON public.loan (copy_id)
    WHERE status = 'ACTIVE';

CREATE INDEX idx_loan_copy_id ON public.loan (copy_id);
CREATE INDEX idx_loan_member_id ON public.loan (member_id);
CREATE INDEX idx_loan_issued_by ON public.loan (issued_by);
CREATE INDEX idx_loan_status ON public.loan (status);
CREATE INDEX idx_loan_issue_date ON public.loan (issue_date);

-- One ACTIVE legacy loan per currently borrowed book. The book_copy created
-- above is unique per book, so each loan points at that book's initial copy.
-- member_id intentionally accepts any existing role, including LIBRARIAN.
INSERT INTO public.loan (
    copy_id,
    member_id,
    issued_by,
    issue_date,
    due_date,
    returned_at,
    status,
    is_legacy
)
SELECT
    c.id,
    b.user_id,
    NULL,
    NULL,
    NULL,
    NULL,
    'ACTIVE',
    true
FROM public.book b
JOIN public.book_copy c ON c.book_id = b.id
WHERE b.user_id IS NOT NULL;
