-- V5: member-submitted password reset requests reviewed by staff.
--
-- A member submits a request anonymously and it starts as PENDING. A LIBRARIAN
-- or ADMIN either rejects it or approves it. Approval issues a temporary
-- password and forces a change at the member's next login.
--
-- Completed requests stay in this table as history so a request can never be
-- approved or rejected twice.

CREATE TABLE public.password_reset_request (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME public.password_reset_request_id_seq
        START WITH 1
        INCREMENT BY 1
        NO MINVALUE
        NO MAXVALUE
        CACHE 1
    ),
    user_id integer NOT NULL,
    requested_at timestamp with time zone NOT NULL,
    status character varying(16) NOT NULL DEFAULT 'PENDING',
    reviewed_by integer,
    reviewed_at timestamp with time zone,
    CONSTRAINT password_reset_request_pkey PRIMARY KEY (id),
    CONSTRAINT password_reset_request_user_id_fkey FOREIGN KEY (user_id) REFERENCES public.users(id),
    CONSTRAINT password_reset_request_reviewed_by_fkey FOREIGN KEY (reviewed_by) REFERENCES public.users(id),
    CONSTRAINT password_reset_request_status_check CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_password_reset_request_user_id ON public.password_reset_request (user_id);
CREATE INDEX idx_password_reset_request_status ON public.password_reset_request (status);
CREATE INDEX idx_password_reset_request_requested_at ON public.password_reset_request (requested_at);

-- A member may have at most one PENDING password reset request.
-- APPROVED and REJECTED rows are excluded so request history is preserved.
CREATE UNIQUE INDEX uq_password_reset_request_pending_user
    ON public.password_reset_request (user_id)
    WHERE status = 'PENDING';
